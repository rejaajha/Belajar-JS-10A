//Operator Logika

//&&
let a = 5 === 5 && 6 < 3; //nilai 1 dan 2 true
console.log(("Hasil operator logika && :" + a)); //True


// || (or)
let d = 10 <= 10 || 10 != '10';
console.log(("Hasil operator logika || :" + d)); //True


// ! (not)
let b = 5 < 10;
